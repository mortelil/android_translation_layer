"""Synthetic media root for the Rhythm library-scan probe.

    fixtures.py OUTPUT_DIR [--clean]

The file names deliberately carry NO metadata: the only source of truth for a
track's properties is its container header. That is what makes the app's own
persisted rows (songs.sampleRate / channels / duration / codec in
`rhythm_database`) a real observation and not a filename echo.

Four containers with four distinct property sets, so every value a row reports
is attributable:

    atl-media-01.wav  PCM s16le   44100 Hz  stereo  2.50 s
    atl-media-02.wav  PCM u8      22050 Hz  mono    3.50 s
    atl-media-03.mp3  MPEG layer3 48000 Hz  mono    1.75 s
    atl-media-04.flac FLAC        96000 Hz  stereo  1.25 s

WAVs are built with the stdlib `wave` module; MP3/FLAC with the host ffmpeg.
The manifest records the constructed properties, the byte sizes, the sha256
digests and the ffprobe reading of each file as an independent cross-check.
"""
import hashlib
import math
import os
import shutil
import struct
import subprocess
import sys
import wave

# name -> (rate, channels, sampwidth_bytes, seconds)  sampwidth 1 = u8, 2 = s16le
WAVS = {
    "atl-media-01.wav": (44100, 2, 2, 2.5),
    "atl-media-02.wav": (22050, 1, 1, 3.5),
}
# name -> (ffmpeg codec args, rate, channels, seconds)
FFMPEG = {
    "atl-media-03.mp3": (["-c:a", "libmp3lame", "-b:a", "64k"], 48000, 1, 1.75),
    "atl-media-04.flac": (["-c:a", "flac"], 96000, 2, 1.25),
}

# What the ATL MediaExtractor reports for each fixture (libavformat headers).
EXPECTED = {
    "atl-media-01.wav": dict(sample_rate=44100, channels=2, bits=16,
                             duration_ms=2500, mime="audio/raw"),
    "atl-media-02.wav": dict(sample_rate=22050, channels=1, bits=8,
                             duration_ms=3500, mime="audio/raw"),
    "atl-media-03.mp3": dict(sample_rate=48000, channels=1, bits=0,
                             duration_ms=1750, mime="audio/mpeg"),
    "atl-media-04.flac": dict(sample_rate=96000, channels=2, bits=16,
                              duration_ms=1250, mime="audio/flac"),
}


def write_wav(path, rate, channels, sampwidth, seconds):
    frames = int(rate * seconds)
    pcm = bytearray()
    for i in range(frames):
        value = math.sin(2.0 * math.pi * 440.0 * i / rate)
        for _ in range(channels):
            if sampwidth == 1:
                pcm.append(int(127 + 100 * value) & 0xFF)
            else:
                pcm += struct.pack("<h", int(20000 * value))
    with wave.open(path, "wb") as w:
        w.setnchannels(channels)
        w.setsampwidth(sampwidth)
        w.setframerate(rate)
        w.writeframes(bytes(pcm))


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def ffprobe(path):
    """Independent reading of the container header (host ffmpeg)."""
    try:
        out = subprocess.run(
            ["ffprobe", "-v", "error", "-show_entries",
             "stream=sample_rate,channels,bits_per_raw_sample,codec_name,duration",
             "-of", "default=noprint_wrappers=1", path],
            check=True, capture_output=True, text=True).stdout
    except (OSError, subprocess.CalledProcessError) as exc:
        return "ffprobe unavailable: %s" % exc
    return " ".join(out.split())


def main():
    if len(sys.argv) < 2:
        sys.exit("usage: fixtures.py OUTPUT_DIR [--clean]")
    out = os.path.abspath(sys.argv[1])
    if "--clean" in sys.argv and os.path.isdir(out):
        shutil.rmtree(out)
    os.makedirs(out, exist_ok=True)

    for name, (rate, channels, sampwidth, seconds) in WAVS.items():
        write_wav(os.path.join(out, name), rate, channels, sampwidth, seconds)

    for name, (codec, rate, channels, seconds) in FFMPEG.items():
        subprocess.run(
            ["ffmpeg", "-y", "-loglevel", "error",
             "-f", "lavfi", "-i",
             "sine=frequency=440:sample_rate=%d:duration=%.3f" % (rate, seconds),
             "-ac", str(channels), "-ar", str(rate)] + codec +
            [os.path.join(out, name)],
            check=True)

    lines = ["# synthetic media root for the Rhythm scan probe",
             "# generated by tests/media-scan/fixtures.py; names carry no metadata"]
    for name in sorted(os.listdir(out)):
        path = os.path.join(out, name)
        if name in EXPECTED and os.path.isfile(path):
            lines.append("fixture %s bytes=%d sha256=%s"
                         % (name, os.path.getsize(path), sha256(path)))
            exp = EXPECTED[name]
            lines.append("  constructed: rate=%d channels=%d bits=%d duration_ms=%d mime=%s"
                         % (exp["sample_rate"], exp["channels"], exp["bits"],
                            exp["duration_ms"], exp["mime"]))
            lines.append("  ffprobe:     %s" % ffprobe(path))
    text = "\n".join(lines) + "\n"
    with open(os.path.join(out, "manifest.txt"), "w") as f:
        f.write(text)
    sys.stdout.write(text)


if __name__ == "__main__":
    main()
