"""Generate the synthetic audio fixtures for the media-extractor probe.

    fixtures.py OUTPUT_DIR [--clean]

Writes only inside OUTPUT_DIR. PCM WAVs are built with the stdlib `wave`
module; the MP3/FLAC containers are produced by ffmpeg (libmp3lame, flac) so a
second and third real container format is exercised. A machine-readable
manifest of the constructed properties and sha256 digests is printed and stored
in OUTPUT_DIR/manifest.txt as evidence.
"""
import hashlib
import math
import os
import shutil
import struct
import subprocess
import sys
import wave

# name -> constructed properties used by ExtractorProbe
WAVS = {
    "tone-44100-stereo-16bit.wav": (44100, 2, 2, 2.0),   # rate, channels, sampwidth, seconds
    "tone-22050-mono-8bit.wav": (22050, 1, 1, 3.0),
}
FFMPEG = {
    "tone-48000-mono.mp3": (["-c:a", "libmp3lame", "-b:a", "64k"], 48000, 1, 1.5),
    "tone-32000-stereo.flac": (["-c:a", "flac"], 32000, 2, 1.0),
}


def write_wav(path, rate, channels, sampwidth, seconds):
    frames = int(rate * seconds)
    pcm = bytearray()
    for i in range(frames):
        value = math.sin(2.0 * math.pi * 440.0 * i / rate)
        for _ in range(channels):
            if sampwidth == 1:
                pcm.append(int(127 + 100 * value) & 0xFF)
            else:
                pcm += struct.pack("<h", int(20000 * value))
    with wave.open(path, "wb") as w:
        w.setnchannels(channels)
        w.setsampwidth(sampwidth)
        w.setframerate(rate)
        w.writeframes(bytes(pcm))


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def main():
    if len(sys.argv) < 2:
        sys.exit("usage: fixtures.py OUTPUT_DIR [--clean]")
    out = os.path.abspath(sys.argv[1])
    if "--clean" in sys.argv and os.path.isdir(out):
        shutil.rmtree(out)
    os.makedirs(out, exist_ok=True)

    for name, (rate, channels, sampwidth, seconds) in WAVS.items():
        write_wav(os.path.join(out, name), rate, channels, sampwidth, seconds)

    for name, (codec, rate, channels, seconds) in FFMPEG.items():
        subprocess.run(
            ["ffmpeg", "-y", "-loglevel", "error",
             "-f", "lavfi", "-i",
             "sine=frequency=440:sample_rate=%d:duration=%.3f" % (rate, seconds),
             "-ac", str(channels), "-ar", str(rate)] + codec +
            [os.path.join(out, name)],
            check=True)

    # WAV with a 1000-byte junk prefix: exercises setDataSource(fd, offset, length).
    with open(os.path.join(out, "tone-44100-stereo-16bit.wav"), "rb") as f:
        wav_bytes = f.read()
    with open(os.path.join(out, "wrapped-tone.wav"), "wb") as f:
        f.write(b"\x00" * 1000)
        f.write(wav_bytes)

    open(os.path.join(out, "empty.bin"), "wb").close()
    with open(os.path.join(out, "malformed.wav"), "wb") as f:
        f.write(b"RIFF")
        f.write(struct.pack("<I", 0x7FFFFFFF))
        f.write(b"WAVEfmt ")
        f.write(b"\x00" * 200)
    with open(os.path.join(out, "not-media.txt"), "wb") as f:
        f.write(b"This is a plain text file, not an audio container.\n" * 4)
    os.makedirs(os.path.join(out, "subdir"), exist_ok=True)

    lines = ["# synthetic media fixtures, generated by tests/media-extractor/fixtures.py"]
    for name in sorted(os.listdir(out)):
        path = os.path.join(out, name)
        if os.path.isfile(path):
            lines.append("%s  bytes=%d  sha256=%s" % (name, os.path.getsize(path), sha256(path)))
    lines.append("expected: tone-44100-stereo-16bit.wav rate=44100 channels=2 bits=16 duration_ms=2000 mime=audio/raw")
    lines.append("expected: tone-22050-mono-8bit.wav    rate=22050 channels=1 bits=8  duration_ms=3000 mime=audio/raw")
    lines.append("expected: tone-48000-mono.mp3        rate=48000 channels=1 mime=audio/mpeg")
    lines.append("expected: tone-32000-stereo.flac     rate=32000 channels=2 bits=16 mime=audio/flac")
    lines.append("expected: wrapped-tone.wav           1000-byte junk prefix then the 16-bit stereo WAV")
    text = "\n".join(lines) + "\n"
    with open(os.path.join(out, "manifest.txt"), "w") as f:
        f.write(text)
    sys.stdout.write(text)


if __name__ == "__main__":
    main()
